// ── 距折线最近距离 ──
export function distToPolyline(x, z, poly) {
  let best = Infinity;
  for (let i = 0; i < poly.length - 1; i++) {
    const [ax, az] = poly[i], [bx, bz] = poly[i + 1];
    const dx = bx - ax, dz = bz - az;
    const l2 = dx * dx + dz * dz;
    let t = l2 > 0 ? ((x - ax) * dx + (z - az) * dz) / l2 : 0;
    t = t < 0 ? 0 : t > 1 ? 1 : t;
    best = Math.min(best, Math.hypot(x - (ax + dx * t), z - (az + dz * t)));
  }
  return best;
}

// ── 冲沟/支沟下切量（供高度场；渐灭段由各沟 fade 参数处理） ──
export function ravineCarve(x, z) {
  let carve = 0;
  for (const r of PK_RAVINES) {
    const d = distToPolyline(x, z, r.pts);
    const full = r.half * 0.42;                       // 沟底平段
    const edge = r.half + r.slopeW;                   // 岸坡外缘
    let k = 1 - sstep3(d, full, edge);
    if (r.fadeX0 !== undefined) k *= 1 - sstep3(x, r.fadeX0, r.fadeX1);       // 东西渐灭
    if (r.fadeZ) k *= sstep3(-z, -r.fadeZ[0][1], -r.fadeZ[0][0]) * (1 - sstep3(z, r.fadeZ[1][0], r.fadeZ[1][1]));
    if (r.fadeX) k *= sstep3(x, r.fadeX[0], r.fadeX[1]) * (1 - sstep3(x, r.fadeX[2], r.fadeX[3]));
    if (r.fadeZ1) k *= 1 - sstep3(-z, r.fadeZ1[0], r.fadeZ1[1]);
    if (r.fadeZ2) k *= 1 - sstep3(z, r.fadeZ2[0], r.fadeZ2[1]);
    carve = Math.max(carve, r.depth * k);
  }
  return carve;
}
function sstep3(v, a, b) {
  const t = Math.max(0, Math.min(1, (v - a) / (b - a)));
  return t * t * (3 - 2 * t);
}
